_BY_ID = {model['id']: model for model in MODEL_REGISTRY}
_BY_NAME = {model['name'].lower(): model for model in MODEL_REGISTRY}


def model_definition(name):
    if not name:
        return None
    value = str(name).strip()
    return _BY_ID.get(value) or _BY_NAME.get(value.lower())


def is_provider_model(name, provider):
    return (model_definition(name) or {}).get('provider') == provider


def provider_model_id(name, env=None):
    env = os.environ if env is None else env
    model = model_definition(name)
    if model is None:
        return None
    return env.get(model.get('providerModelEnv', '')) or model.get('providerModelId')


def capability(name, key, fallback=False):
    return (model_definition(name) or {}).get('capabilities', {}).get(key, fallback)


def retirement_message(name):
    """The refusal for a new job on a retired model, naming its replacement; None while the model is current."""
    model = model_definition(name)
    if not model or not model.get('retiredFor'):
        return None
    replacement = model_definition(model['retiredFor'])
    return f'{model["name"]} has been retired. Choose {replacement["name"]} instead.'
